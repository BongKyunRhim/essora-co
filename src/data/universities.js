// De-duplicate labels (some entries may repeat)
const seen = new Set();
export const UNIVERSITIES = RAW.filter(({ label }) => {
  if (seen.has(label)) return false;
  seen.add(label);
  return true;
}).map(({ label, s }) => ({ label, terms: s.toLowerCase() }));

export function searchUniversities(query) {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return UNIVERSITIES.filter((u) => u.terms.includes(q) || u.label.toLowerCase().includes(q)).slice(0, 8);
}
